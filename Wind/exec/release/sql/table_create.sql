CREATE TABLE IF NOT EXISTS table_user
(
	user_id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
	account VARCHAR(64) NOT NULL,
	password_hash BINARY(32) NOT NULL,
	password_salt BINARY(16) NOT NULL,
	status TINYINT UNSIGNED NOT NULL DEFAULT 1,
	created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
	updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
	PRIMARY KEY (user_id),
	UNIQUE KEY uk_table_user_account (account)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;

CREATE TABLE IF NOT EXISTS table_strategy
(
	strategy_id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
	account_id BIGINT UNSIGNED NOT NULL DEFAULT 1,
	strategy_type VARCHAR(64) NOT NULL,
	strategy_name VARCHAR(128) NOT NULL,
	parameters JSON NOT NULL,
	subscriptions JSON NOT NULL,
	event_queue_limit INT UNSIGNED NOT NULL DEFAULT 4096,
	auto_start TINYINT UNSIGNED NOT NULL DEFAULT 0,
	enabled TINYINT UNSIGNED NOT NULL DEFAULT 1,
	created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
	updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
	PRIMARY KEY (strategy_id),
	UNIQUE KEY uk_table_strategy_name (strategy_name),
	KEY idx_table_strategy_enabled (enabled)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;

CREATE TABLE IF NOT EXISTS table_trading_account
(
 account_id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
 name VARCHAR(128) NOT NULL,
 account_type INT NOT NULL DEFAULT 0,
 adapter_key VARCHAR(64) NOT NULL DEFAULT 'simulated',
 broker VARCHAR(128) NOT NULL DEFAULT 'wind_simulated',
 site VARCHAR(128) NOT NULL DEFAULT 'default',
 external_account VARCHAR(128) NOT NULL DEFAULT '',
 initial_balance BIGINT NOT NULL,
 is_default TINYINT NOT NULL DEFAULT 0,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 PRIMARY KEY(account_id),
 UNIQUE KEY uk_account_name(name)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;

CREATE TABLE IF NOT EXISTS table_account_log
(
 log_id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
 account_id BIGINT UNSIGNED NOT NULL,
 actor VARCHAR(128) NOT NULL,
 action VARCHAR(64) NOT NULL,
 message TEXT NOT NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 PRIMARY KEY(log_id),
 KEY idx_account_log(account_id,log_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
